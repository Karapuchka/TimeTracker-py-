def simple_stem(word: str) -> str:
    """
    Простейший стемминг: отсечение распространенных окончаний.

    Аргументы:
        word: слово в нижнем регистре

    Возвращает:
        основа слова
    """
    if len(word) < 4:
        return word  # короткие слова не обрабатываем

    # Сортируем окончания по длине (от длинных к коротким)
    sorted_endings = sorted(ENDINGS, key=len, reverse=True)

    for ending in sorted_endings:
        if word.endswith(ending) and len(word) - len(ending) >= 3:
            return word[:len(word) - len(ending)]

    return word


def build_frequency_dictionary(records: List[WorkRecord]) -> Dict[str, int]:
    """
    Построить частотный словарь на основе описаний в записях.

    Аргументы:
        records: список записей учета рабочего времени

    Возвращает:
        словарь {нормализованное_слово: частота}
    """
    freq_dict = {}

    for rec in records:
        if not rec.description or not rec.description.strip():
            continue

        # Приводим к нижнему регистру
        text = rec.description.lower()

        # Разбиваем на слова (только буквы)
        words = re.findall(r'[а-яё]+', text)

        for word in words:
            if len(word) < 2:
                continue

            # Стемминг
            stemmed = simple_stem(word)

            # Подсчет
            if stemmed in freq_dict:
                freq_dict[stemmed] += 1
            else:
                freq_dict[stemmed] = 1

    return freq_dict